import type { Card } from '../../types/card.js';
import { resolveSetcode } from './engine-data.js';
import { compilePsct, compileSummonProcedure, luaComment, type PsctCompileReport, type PsctCompileOptions } from './psct-compiler.js';

export type { PsctCompileReport } from './psct-compiler.js';

export interface EffectSpec {
  type: string; // 'ignition' | 'trigger' | 'quick' | 'activate' | 'sp_summon' | 'continuous' | string;
  category?: string; // 'CATEGORY_DESTROY' | 'CATEGORY_SPECIAL_SUMMON' | 'CATEGORY_TOHAND' | 'CATEGORY_SEARCH' | etc.
  isHOPT?: boolean;
  targets?: boolean;
  description?: string;
  code?: string; // e.g. 'EVENT_FREE_CHAIN', 'EVENT_SUMMON_SUCCESS', 'EVENT_CHAINING'
  range?: string; // e.g. 'LOCATION_MZONE', 'LOCATION_HAND', 'LOCATION_GRAVE'
}

/**
 * Normalizes category constant string ensuring proper prefix.
 */
function normalizeCategory(cat?: string): string {
  if (!cat) return 'CATEGORY_DESTROY';
  const trimmed = cat.trim();
  const normalized = trimmed.startsWith('CATEGORY_') ? trimmed : `CATEGORY_${trimmed.toUpperCase().replace(/\s+/g, '_')}`;
  return isConstantExpr(normalized, 'CATEGORY_') ? normalized : 'CATEGORY_DESTROY';
}

/**
 * Spec fields (code/range/category) are spliced into Lua as code, so they must
 * be engine constant expressions such as `EVENT_PHASE+PHASE_END`, nothing else.
 */
function isConstantExpr(value: string, prefix: string): boolean {
  if (value.length > 120) return false;
  if (!/^[A-Z][A-Z0-9_]*(?:\s*[+|]\s*[A-Z][A-Z0-9_]*)*$/.test(value)) return false;
  return value.split(/\s*[+|]\s*/).every((part) => part.startsWith(prefix) || /^(PHASE|LOCATION)_/.test(part));
}

function sanitizeSpec(spec: EffectSpec): EffectSpec {
  return {
    ...spec,
    type: String(spec.type || 'ignition'),
    description: spec.description ? luaComment(spec.description) : undefined,
    code: spec.code && isConstantExpr(spec.code.trim(), 'EVENT_') ? spec.code.trim() : undefined,
    range: spec.range && isConstantExpr(spec.range.trim(), 'LOCATION_') ? spec.range.trim() : undefined,
  };
}

/**
 * Compiles a custom card from its text and returns the Lua plus a coverage
 * report (which effects were understood, what was skipped, design warnings).
 */
export function compileCustomCard(card: Partial<Card>, id: number, opts: PsctCompileOptions = {}): PsctCompileReport {
  return compilePsct(card, id, opts);
}

/**
 * Generates an EDOPro / ProjectIgnis ocgcore Lua script for a custom card.
 *
 * - With `effectsSpec`: the caller describes each effect explicitly (legacy path).
 * - Without it: the card text is compiled by the PSCT compiler, so the script
 *   does what the card says instead of a canned "search any card" template.
 */
export function generateLuaScript(
  card: Partial<Card>,
  id: number,
  effectsSpec?: EffectSpec[]
): string {
  if (!effectsSpec || effectsSpec.length === 0) return compilePsct(card, id).lua;
  if (!Number.isSafeInteger(id) || id <= 0) throw new Error(`Invalid card id ${String(id)}: expected a positive integer passcode`);
  return generateFromSpec(card, id, effectsSpec.map(sanitizeSpec));
}

function generateFromSpec(card: Partial<Card>, id: number, specs: EffectSpec[]): string {
  const cardName = card.name || 'Custom Card';
  const cardType = `${card.type || ''} ${card.frameType || ''}`.toLowerCase();
  const isCounterTrap = /\btrap\b/.test(cardType) && /counter/.test(cardType);
  const archetype = String(card.archetype || '').split(/[,/]/)[0].trim();

  const lines: string[] = [];
  lines.push(`-- Custom Card: ${luaComment(cardName, 120)} (ID: ${id})`);
  lines.push(`-- Generated by Yu-Gi-Oh! Assistant from an explicit effect spec`);
  lines.push(`local s, id = GetID()`);
  lines.push(`function s.initial_effect(c)`);

  // Summon procedures come from the material line, not from a guessed template.
  const proc = compileSummonProcedure(card, id);
  for (const u of proc.unparsed) lines.push(`\t-- TODO (not understood): ${luaComment(u)}`);
  lines.push(...proc.init);

  specs.forEach((spec, idx) => {
    const effNum = idx + 1;
    const effType = spec.type.toLowerCase();
    const cat = normalizeCategory(spec.category);
    const isTrigger = effType === 'trigger';
    const isNegate = cat === 'CATEGORY_NEGATE';

    lines.push(`\t-- Effect ${effNum}: ${spec.description || spec.type}`);
    lines.push(`\tlocal e${effNum} = Effect.CreateEffect(c)`);
    if (spec.description) lines.push(`\te${effNum}:SetDescription(aux.Stringid(id, ${Math.min(idx, 15)}))`);
    // Searches also move a card to the hand: the engine needs both categories.
    const cats = cat === 'CATEGORY_SEARCH' ? 'CATEGORY_TOHAND + CATEGORY_SEARCH' : isNegate ? 'CATEGORY_NEGATE + CATEGORY_DESTROY' : cat;
    lines.push(`\te${effNum}:SetCategory(${cats})`);

    if (effType === 'activate') {
      lines.push(`\te${effNum}:SetType(EFFECT_TYPE_ACTIVATE)`);
      lines.push(`\te${effNum}:SetCode(${spec.code || 'EVENT_FREE_CHAIN'})`);
    } else if (isTrigger) {
      lines.push(`\te${effNum}:SetType(EFFECT_TYPE_SINGLE + EFFECT_TYPE_TRIGGER_O)`);
      lines.push(`\te${effNum}:SetCode(${spec.code || 'EVENT_SUMMON_SUCCESS'})`);
    } else if (effType === 'quick') {
      lines.push(`\te${effNum}:SetType(EFFECT_TYPE_QUICK_O)`);
      lines.push(`\te${effNum}:SetCode(${spec.code || 'EVENT_FREE_CHAIN'})`);
      lines.push(`\te${effNum}:SetRange(${spec.range || 'LOCATION_MZONE'})`);
    } else if (effType === 'sp_summon' || (effType === 'ignition' && spec.range === 'LOCATION_HAND')) {
      lines.push(`\te${effNum}:SetType(EFFECT_TYPE_IGNITION)`);
      lines.push(`\te${effNum}:SetRange(LOCATION_HAND)`);
    } else if (effType === 'continuous') {
      lines.push(`\te${effNum}:SetType(EFFECT_TYPE_FIELD + EFFECT_TYPE_CONTINUOUS)`);
      lines.push(`\te${effNum}:SetCode(${spec.code || 'EVENT_ADJUST'})`);
      lines.push(`\te${effNum}:SetRange(${spec.range || 'LOCATION_MZONE'})`);
    } else {
      lines.push(`\te${effNum}:SetType(EFFECT_TYPE_IGNITION)`);
      lines.push(`\te${effNum}:SetRange(${spec.range || 'LOCATION_MZONE'})`);
    }

    // One SetProperty call: a second call would overwrite the first flag.
    const props: string[] = [];
    if (isTrigger) props.push('EFFECT_FLAG_DELAY');
    if (spec.targets) props.push('EFFECT_FLAG_CARD_TARGET');
    if (props.length) lines.push(`\te${effNum}:SetProperty(${props.join(' + ')})`);

    // Each hard once-per-turn effect gets its own code so two HOPT effects do not block each other.
    if (spec.isHOPT) lines.push(`\te${effNum}:SetCountLimit(1, {id, ${idx}})`);

    if (isNegate && (spec.code === 'EVENT_CHAINING' || isCounterTrap)) lines.push(`\te${effNum}:SetCondition(s.condition${effNum})`);
    lines.push(`\te${effNum}:SetCost(s.cost${effNum})`);
    lines.push(`\te${effNum}:SetTarget(s.target${effNum})`);
    lines.push(`\te${effNum}:SetOperation(s.operation${effNum})`);
    lines.push(`\tc:RegisterEffect(e${effNum})`);

    if (isTrigger && (!spec.code || spec.code === 'EVENT_SUMMON_SUCCESS')) {
      lines.push(`\tlocal e${effNum}_b = e${effNum}:Clone()`);
      lines.push(`\te${effNum}_b:SetCode(EVENT_SPSUMMON_SUCCESS)`);
      lines.push(`\tc:RegisterEffect(e${effNum}_b)`);
    }
  });

  lines.push(`end`);
  lines.push(``);
  lines.push(...proc.helpers);
  lines.push(``);

  // Archetype filter: numeric setcode, because custom archetypes have no SET_ constant.
  if (archetype) {
    const { setcode } = resolveSetcode(archetype);
    lines.push(`-- Filter for "${luaComment(archetype, 60)}" cards`);
    lines.push(`function s.filter(c)`);
    lines.push(`\treturn c:IsSetCard(0x${setcode.toString(16)}) and c:IsAbleToHand()`);
    lines.push(`end`);
    lines.push(``);
  }

  specs.forEach((spec, idx) => {
    const effNum = idx + 1;
    const cat = normalizeCategory(spec.category);
    const effType = spec.type.toLowerCase();
    const isNegate = cat === 'CATEGORY_NEGATE';

    if (isNegate && (spec.code === 'EVENT_CHAINING' || isCounterTrap)) {
      lines.push(`function s.condition${effNum}(e, tp, eg, ep, ev, re, r, rp)`);
      lines.push(`\treturn Duel.IsChainNegatable(ev)`);
      lines.push(`end`);
      lines.push(``);
    }

    // Costs: the spec carries none, so none is charged (a Counter Trap is not sent to the GY as cost).
    lines.push(`-- Cost for Effect ${effNum}`);
    lines.push(`function s.cost${effNum}(e, tp, eg, ep, ev, re, r, rp, chk)`);
    lines.push(`\tif chk == 0 then return true end`);
    lines.push(`end`);
    lines.push(``);

    lines.push(`-- Target for Effect ${effNum}`);
    lines.push(`function s.target${effNum}(e, tp, eg, ep, ev, re, r, rp, chk, chkc)`);
    if (spec.targets) {
      lines.push(`\tif chkc then return chkc:IsLocation(LOCATION_ONFIELD) and chkc:IsControler(1 - tp) end`);
      lines.push(`\tif chk == 0 then return Duel.IsExistingTarget(nil, tp, 0, LOCATION_ONFIELD, 1, nil) end`);
      lines.push(`\tDuel.Hint(HINT_SELECTMSG, tp, HINTMSG_TARGET)`);
      lines.push(`\tlocal g = Duel.SelectTarget(tp, nil, tp, 0, LOCATION_ONFIELD, 1, 1, nil)`);
      lines.push(`\tDuel.SetOperationInfo(0, ${cat}, g, 1, 0, 0)`);
    } else if (cat === 'CATEGORY_SPECIAL_SUMMON') {
      if (effType === 'sp_summon' || spec.range === 'LOCATION_HAND') {
        lines.push(`\tif chk == 0 then return Duel.GetLocationCount(tp, LOCATION_MZONE) > 0`);
        lines.push(`\t\tand e:GetHandler():IsCanBeSpecialSummoned(e, 0, tp, false, false) end`);
        lines.push(`\tDuel.SetOperationInfo(0, CATEGORY_SPECIAL_SUMMON, e:GetHandler(), 1, 0, 0)`);
      } else {
        lines.push(`\tif chk == 0 then return Duel.GetLocationCount(tp, LOCATION_MZONE) > 0`);
        lines.push(`\t\tand Duel.IsExistingMatchingCard(Card.IsCanBeSpecialSummoned, tp, LOCATION_GRAVE + LOCATION_HAND, 0, 1, nil, e, 0, tp, false, false) end`);
        lines.push(`\tDuel.SetOperationInfo(0, CATEGORY_SPECIAL_SUMMON, nil, 1, tp, LOCATION_GRAVE + LOCATION_HAND)`);
      }
    } else if (cat === 'CATEGORY_SEARCH' || cat === 'CATEGORY_TOHAND') {
      const filter = archetype ? 's.filter' : 'Card.IsAbleToHand';
      lines.push(`\tif chk == 0 then return Duel.IsExistingMatchingCard(${filter}, tp, LOCATION_DECK, 0, 1, nil) end`);
      lines.push(`\tDuel.SetOperationInfo(0, CATEGORY_TOHAND, nil, 1, tp, LOCATION_DECK)`);
    } else if (isNegate) {
      lines.push(`\tif chk == 0 then return true end`);
      lines.push(`\tDuel.SetOperationInfo(0, CATEGORY_NEGATE, eg, 1, 0, 0)`);
      lines.push(`\tif re:GetHandler():IsDestructable() and re:GetHandler():IsRelateToEffect(re) then`);
      lines.push(`\t\tDuel.SetOperationInfo(0, CATEGORY_DESTROY, eg, 1, 0, 0)`);
      lines.push(`\tend`);
    } else {
      lines.push(`\tif chk == 0 then return true end`);
    }
    lines.push(`end`);
    lines.push(``);

    lines.push(`-- Operation for Effect ${effNum}`);
    lines.push(`function s.operation${effNum}(e, tp, eg, ep, ev, re, r, rp)`);
    if (spec.targets) {
      lines.push(`\tlocal tc = Duel.GetFirstTarget()`);
      lines.push(`\tif tc and tc:IsRelateToEffect(e) then`);
      lines.push(`\t\tDuel.Destroy(tc, REASON_EFFECT)`);
      lines.push(`\tend`);
    } else if (cat === 'CATEGORY_SPECIAL_SUMMON') {
      if (effType === 'sp_summon' || spec.range === 'LOCATION_HAND') {
        lines.push(`\tlocal c = e:GetHandler()`);
        lines.push(`\tif c:IsRelateToEffect(e) and Duel.GetLocationCount(tp, LOCATION_MZONE) > 0 then`);
        lines.push(`\t\tDuel.SpecialSummon(c, 0, tp, tp, false, false, POS_FACEUP)`);
        lines.push(`\tend`);
      } else {
        lines.push(`\tif Duel.GetLocationCount(tp, LOCATION_MZONE) <= 0 then return end`);
        lines.push(`\tDuel.Hint(HINT_SELECTMSG, tp, HINTMSG_SPSUMMON)`);
        lines.push(`\tlocal g = Duel.SelectMatchingCard(tp, Card.IsCanBeSpecialSummoned, tp, LOCATION_GRAVE + LOCATION_HAND, 0, 1, 1, nil, e, 0, tp, false, false)`);
        lines.push(`\tif #g > 0 then`);
        lines.push(`\t\tDuel.SpecialSummon(g, 0, tp, tp, false, false, POS_FACEUP)`);
        lines.push(`\tend`);
      }
    } else if (cat === 'CATEGORY_SEARCH' || cat === 'CATEGORY_TOHAND') {
      lines.push(`\tDuel.Hint(HINT_SELECTMSG, tp, HINTMSG_ATOHAND)`);
      lines.push(`\tlocal g = Duel.SelectMatchingCard(tp, ${archetype ? 's.filter' : 'Card.IsAbleToHand'}, tp, LOCATION_DECK, 0, 1, 1, nil)`);
      lines.push(`\tif #g > 0 then`);
      lines.push(`\t\tDuel.SendtoHand(g, nil, REASON_EFFECT)`);
      lines.push(`\t\tDuel.ConfirmCards(1 - tp, g)`);
      lines.push(`\tend`);
    } else if (isNegate) {
      lines.push(`\tif Duel.NegateActivation(ev) and re:GetHandler():IsRelateToEffect(re) then`);
      lines.push(`\t\tDuel.Destroy(eg, REASON_EFFECT)`);
      lines.push(`\tend`);
    } else {
      lines.push(`\t-- TODO (not understood): no resolution for category ${cat}`);
    }
    lines.push(`end`);
    lines.push(``);
  });

  return lines.join('\n');
}
